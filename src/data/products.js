export const getFeaturedProducts = () => products.slice(0, 8);
export const getBestSellers = () => products.filter(p => p.badge === 'Best Seller');
export const getProductById = (id) => products.find(p => p.id === id || p.slug === id);
export const getProductsByCategory = (cat) => products.filter(p => p.subcategory === cat || p.category === cat);
export const getProductsBySearch = (q) => {
  const query = q.toLowerCase();
  return products.filter(p =>
    p.name.toLowerCase().includes(query) ||
    p.description.toLowerCase().includes(query) ||
    p.tags.some(t => t.includes(query))
  );
};
